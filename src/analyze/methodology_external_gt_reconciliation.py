"""
Appendix: reconciliation of OpenReview rows with external pre/post scores.

The bundled parquet files contain the row-level result of matching OpenReview
reviews to the external Kargaran et al. / papercopilot-iclr-insights
pre/post-rebuttal scores. The external source also has paper-level entries
whose review dictionaries are empty; those paper-level empty entries are not
representable as review rows in the parquet. For transparency, this script
combines the reproduced row-level match with the archived external snapshot
paper counts reported in the appendix.

Outputs:
  data/results/methodology/external_gt_reconciliation/reconciliation_by_year.csv
  data/results/methodology/external_gt_reconciliation/reconciliation_summary.md

Usage:
  python src/analyze/methodology_external_gt_reconciliation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

_src = Path(__file__).resolve().parent.parent
if str(_src) not in sys.path:
    sys.path.insert(0, str(_src))

import pandas as pd

from core.paths import PROCESSED_DATA_DIR, RESULTS_DIR


PARQUET_DIR = PROCESSED_DATA_DIR / "parquet"
OUT_DIR = RESULTS_DIR / "methodology" / "external_gt_reconciliation"

# Archived paper-level counts from the external Kargaran et al. snapshot used
# in the paper. These counts live above the review-row level: empty external
# entries have no reviewer rows, so they cannot be recovered from parquet alone.
EXTERNAL_SNAPSHOT = {
    2024: {"total_paper_entries": 7407, "empty_paper_entries": 434},
    2025: {"total_paper_entries": 11677, "empty_paper_entries": 246},
}


def _load_year(year: int) -> pd.DataFrame:
    path = PARQUET_DIR / f"iclr_{year}_reviews.parquet"
    if not path.exists():
        raise FileNotFoundError(f"Missing review parquet for ICLR {year}: {path}")
    df = pd.read_parquet(path)
    df["year"] = year
    return df


def _summarize_year(year: int) -> dict:
    df = _load_year(year)
    has_ext = df["ext_rating_before"].notna() & df["ext_rating_after"].notna()
    ext = df[has_ext].copy()
    no_ext = df[~has_ext].copy()

    if "rating" not in ext.columns:
        raise ValueError("Expected OpenReview final rating column `rating` in parquet")

    rating_match = (
        pd.to_numeric(ext["rating"], errors="coerce")
        == pd.to_numeric(ext["ext_rating_after"], errors="coerce")
    )

    snapshot = EXTERNAL_SNAPSHOT[year]
    external_with_score_papers = (
        snapshot["total_paper_entries"] - snapshot["empty_paper_entries"]
    )
    missing_ext_papers_with_reviews = no_ext["forum"].nunique()
    missing_ext_reviews_with_reviews = len(no_ext)
    empty_external_no_review_papers = (
        snapshot["empty_paper_entries"] - missing_ext_papers_with_reviews
    )

    return {
        "year": year,
        "openreview_papers_with_reviews": int(df["forum"].nunique()),
        "openreview_reviews": int(len(df)),
        "external_total_paper_entries": int(snapshot["total_paper_entries"]),
        "external_paper_entries_with_reviewer_scores_reported": int(external_with_score_papers),
        "external_empty_paper_entries_reported": int(snapshot["empty_paper_entries"]),
        "matched_papers_with_external_scores_in_parquet": int(ext["forum"].nunique()),
        "matched_reviews_in_both": int(len(ext)),
        "reviews_only_in_openreview": int(len(no_ext)),
        "empty_external_entries_with_openreview_reviews": int(missing_ext_papers_with_reviews),
        "reviews_on_empty_external_entries": int(missing_ext_reviews_with_reviews),
        "empty_external_entries_with_no_openreview_reviews": int(empty_external_no_review_papers),
        "openreview_final_equals_external_after_n": int(rating_match.sum()),
        "openreview_final_equals_external_after_pct": float(rating_match.mean() * 100.0),
        "openreview_final_external_after_mismatches": int((~rating_match).sum()),
    }


def _write_markdown(rows: list[dict], path: Path) -> None:
    total_reviews = sum(r["matched_reviews_in_both"] for r in rows)
    total_empty = sum(r["external_empty_paper_entries_reported"] for r in rows)
    total_case1 = sum(r["empty_external_entries_with_openreview_reviews"] for r in rows)
    total_case1_reviews = sum(r["reviews_on_empty_external_entries"] for r in rows)
    total_case2 = sum(r["empty_external_entries_with_no_openreview_reviews"] for r in rows)

    lines = [
        "# External Ground-Truth Reconciliation",
        "",
        "This file is generated by `src/analyze/methodology_external_gt_reconciliation.py`.",
        "",
        "The review-level reconciliation is reproduced from the bundled parquet files. "
        "The paper-level external totals and empty-entry counts come from the archived "
        "Kargaran et al. / papercopilot-iclr-insights snapshot used in the appendix; "
        "empty paper entries have no reviewer rows and therefore cannot be inferred "
        "from the review parquet alone.",
        "",
        "| Year | OpenReview reviews | Matched reviews | Only in OpenReview | Final rating = external after | Empty ext. with reviews | Empty ext. no reviews |",
        "|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['year']} | {r['openreview_reviews']:,} | "
            f"{r['matched_reviews_in_both']:,} | {r['reviews_only_in_openreview']:,} | "
            f"{r['openreview_final_equals_external_after_pct']:.1f}% | "
            f"{r['empty_external_entries_with_openreview_reviews']:,} | "
            f"{r['empty_external_entries_with_no_openreview_reviews']:,} |"
        )
    lines.extend([
        "",
        f"Combined matched review rows: {total_reviews:,}.",
        f"External empty paper entries: {total_empty:,}.",
        f"Case 1, empty external entries that have OpenReview reviews: {total_case1:,} "
        f"papers covering {total_case1_reviews:,} reviews.",
        f"Case 2, empty external entries with no OpenReview reviews: {total_case2:,} papers.",
        "",
        "The OpenReview `rating` column matches the external post-rebuttal score for "
        "100% of matched review rows in both years. The appropriate score-decoder "
        "ground truth is therefore `ext_rating_before`, not the final OpenReview rating.",
    ])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = [_summarize_year(year) for year in (2024, 2025)]
    out = pd.DataFrame(rows)
    csv_path = OUT_DIR / "reconciliation_by_year.csv"
    md_path = OUT_DIR / "reconciliation_summary.md"
    out.to_csv(csv_path, index=False)
    _write_markdown(rows, md_path)

    print(f"Wrote: {csv_path}")
    print(f"Wrote: {md_path}")
    print()
    print(out[[
        "year",
        "openreview_reviews",
        "matched_reviews_in_both",
        "reviews_only_in_openreview",
        "openreview_final_equals_external_after_pct",
    ]].to_string(index=False))


if __name__ == "__main__":
    main()
